def get_curated_compatibility_copy(dog_element, relationship_type, version):
    template = COMPATIBILITY_COPY.get((relationship_type, version)) or COMPATIBILITY_COPY.get((relationship_type, 'A'))
    if template is None:
        raise KeyError(f'Unsupported compatibility copy: {relationship_type}/{version}')

    element = ELEMENT_LABELS.get(dog_element, dog_element)
    relationship = RELATIONSHIP_LABELS.get(relationship_type, relationship_type)

    return {
        'score': template['score'],
        'title': template['title'],
        'description': template['description'].format(element=element, relationship=relationship),
        'advice': template['advice'],
    }
